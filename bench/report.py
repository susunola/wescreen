#!/usr/bin/env python3
"""Turn bench/results/*.jsonl into a Markdown report.

    python3 bench/report.py > bench/RESULTS.md

The headline table answers one question: at the same text-edge quality, how many bytes does each
encoder need compared with a baseline? Sizes are interpolated in log-size between measured points and
reported only inside the measured range, never extrapolated.
"""
import argparse
import collections
import json
import math
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from metrics import size_at_quality  # noqa: E402

BENCH = Path(__file__).resolve().parent
TIMING_LIMIT = 3.0  # mean frame shift above which content matching cannot be trusted
ANCHOR = 'browser: MediaRecorder vp9|standard'
TARGETS = (30.0, 35.0)  # edge PSNR in dB: roughly "text is soft" and "text is clean"


def load_rows(paths):
    rows = []
    for path in paths:
        if path.exists():
            rows += [json.loads(line) for line in path.read_text().splitlines() if line.strip()]
    return rows


def group_key(row):
    return f'{row["source"]}: {row["encoder"]}'


def timing_limited(row):
    return row['encoder'].startswith('MediaRecorder') and (row.get('mean_shift') or 0) > TIMING_LIMIT


def build_tables(rows, baseline):
    by_clip = collections.defaultdict(lambda: collections.defaultdict(list))
    for row in rows:
        if timing_limited(row):
            continue
        by_clip[row['clip']][group_key(row)].append(row)
    interpolated = {}
    for clip, groups in by_clip.items():
        for name, points in groups.items():
            for target in TARGETS:
                size = size_at_quality(points, 'edge_psnr', target)
                if size is not None:
                    interpolated[(clip, name, target)] = size
    ratios = collections.defaultdict(list)
    for (clip, name, target), size in interpolated.items():
        base = interpolated.get((clip, baseline, target))
        if base:
            ratios[(name, target)].append(size / base)
    return by_clip, interpolated, ratios





def operating_point(rows, anchor):
    """What each encoder needs to match the quality `anchor` reaches, as a fraction of anchor's bytes.

    anchor is "source: encoder|param", e.g. the extension's current default. Clips whose anchor row is
    timing-limited (frames dropped or retimed by real-time capture) are excluded and returned separately.
    """
    name, param = anchor.split('|')
    by = collections.defaultdict(lambda: collections.defaultdict(list))
    for row in rows:
        by[row['clip']][group_key(row)].append(row)
    ratios, excluded = collections.defaultdict(list), []
    for clip, groups in by.items():
        base = next((r for r in groups.get(name, []) if r['param'].startswith(param)), None)
        if not base or base.get('edge_psnr') is None:
            continue
        if (base.get('mean_shift') or 0) > TIMING_LIMIT:
            excluded.append(clip)
            continue
        for other, points in groups.items():
            if other == name:
                continue
            size = size_at_quality(points, 'edge_psnr', base['edge_psnr'])
            if size:
                ratios[other].append((clip, size / base['bytes']))
    return ratios, excluded


def geometric_mean(values):
    return math.exp(sum(math.log(v) for v in values) / len(values))


def render(rows, baseline):
    by_clip, interpolated, ratios = build_tables(rows, baseline)
    out = ['# Encoder benchmark results', '']
    browsers = sorted({r.get('browser', '') for r in rows if r.get('browser')})
    out += ['Generated by `bench/report.py` from `bench/results/*.jsonl`.', '']
    if browsers:
        out += ['Browser(s): ' + '; '.join(f'`{b}`' for b in browsers), '']
    out += ['## Bytes needed at equal text-edge quality, relative to `' + baseline + '`', '',
            'Lower is better. Geometric mean over the clips where both encoders reach the target inside their measured range. '
            '"n" is how many clips that is; a ratio built from one clip is anecdote, not a finding.', '',
            '| Encoder | ' + ' | '.join(f'edge PSNR {t:.0f} dB' for t in TARGETS) + ' |', '|---|' + '---|' * len(TARGETS)]
    names = sorted({name for (_, name, _) in interpolated})
    for name in names:
        cells = []
        for target in TARGETS:
            values = ratios.get((name, target), [])
            cells.append(f'{geometric_mean(values):.2f}× (n={len(values)})' if values else '—')
        out.append(f'| {name} | ' + ' | '.join(cells) + ' |')
    ratios2, excluded = operating_point(rows, ANCHOR)
    out += ['', '## Bytes to match what the extension records today', '',
            f'Anchor: `{ANCHOR.replace("|", " ")}` (current default). For each clip, the size an encoder needs to reach the anchor\'s edge PSNR, divided by the anchor\'s size. Below 1.00× means smaller at equal text sharpness; "—" means the encoder never reached that quality in the measured range. Geometric mean; n is the number of clips.', '']
    if excluded:
        out += ['Excluded as timing-limited (real-time MediaRecorder dropped or retimed frames, so pixel comparison against the reference is not meaningful): ' + ', '.join(f'`{c}`' for c in sorted(excluded)) + '.', '']
    if not ratios2:
        out += ['No clip produced a trustworthy MediaRecorder anchor in this run, so no ratio is given. Re-run `browser_bench.mjs` on an idle, real machine (headed, not under CPU load) before drawing conclusions about MediaRecorder.', '']
    else:
        out += ['| Encoder | Relative size | n |', '|---|---:|---:|']
    for name in sorted(ratios2):
        vals = [v for _, v in ratios2[name]]
        out.append(f'| {name} | {geometric_mean(vals):.2f}× | {len(vals)} |')
    out += ['', '## How far to trust this', '',
            '- Rows marked ⚠ come from real-time MediaRecorder capture whose output timeline could not be aligned with the reference (`mean_shift` > ' + str(int(TIMING_LIMIT)) + ' frames, or more frames than the clip has). On a loaded or headless machine this says more about capture timing than about the encoder, so those rows are not used for any ratio above.',
            '- WebCodecs and FFmpeg rows use exact frame timestamps and decode 1:1 (`mean_shift` ≈ 0 for the former), so comparisons between them are sound for the synthetic corpus.',
            '- Synthetic content, software encoders only: hardware H.264/HEVC/AV1 and real screen captures are not covered by this run.', '', '## Per-clip measurements', '']
    for clip in sorted(by_clip):
        out += [f'### {clip}', '', '| Encoder | Setting | kbps | MB/min | SSIM | Edge PSNR | Frames out/expected |', '|---|---|---:|---:|---:|---:|---:|']
        for name in sorted(by_clip[clip]):
            for row in sorted(by_clip[clip][name], key=lambda r: r['kbps']):
                flag = ' ⚠' if (row.get('mean_shift') or 0) > TIMING_LIMIT else ''
                out.append(f'| {name} | {row["param"]}{flag} | {row["kbps"]:.0f} | {row["mb_per_min"]:.2f} | {row["ssim"]} | {row["edge_psnr"]} | {row["frames_decoded"]}/{row["frames_expected"]} |')
        out.append('')
    return '\n'.join(out)


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument('--results', nargs='*', default=[str(BENCH / 'results' / 'ffmpeg.jsonl'), str(BENCH / 'results' / 'browser.jsonl')])
    parser.add_argument('--baseline', default='ffmpeg: x264')
    args = parser.parse_args(argv)
    rows = load_rows([Path(p) for p in args.results])
    if not rows:
        print('no results found', file=sys.stderr)
        return 1
    print(render(rows, args.baseline))
    return 0


if __name__ == '__main__':
    sys.exit(main())
